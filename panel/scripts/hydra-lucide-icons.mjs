/*
 * Hydra: exports every Lucide icon (from the "lucide" package, same version as
 * "lucide-react") as data, so icons can be picked by name in the admin area.
 *
 *   public/hydra/lucide.json      name => [[tag, attributes], …] for the icon picker
 *   resources/icons/lucide.php    the same as PHP array for server side rendering
 *
 * Run "yarn hydra:icons" after updating Lucide and commit both files.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'node_modules/lucide/dist/esm/icons');
const version = JSON.parse(readFileSync(join(root, 'node_modules/lucide/package.json'), 'utf8')).version;

const icons = {};
for (const file of readdirSync(source).filter((name) => name.endsWith('.mjs')).sort()) {
    const { default: nodes } = await import(pathToFileURL(join(source, file)).href);
    icons[file.replace(/\.mjs$/, '')] = nodes;
}

const php = (value) => {
    if (Array.isArray(value)) return `[${value.map(php).join(',')}]`;
    if (value !== null && typeof value === 'object') {
        return `[${Object.entries(value).map(([key, item]) => `${php(key)}=>${php(item)}`).join(',')}]`;
    }

    return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
};

writeFileSync(join(root, 'public/hydra/lucide.json'), JSON.stringify({ version, icons }));

mkdirSync(join(root, 'resources/icons'), { recursive: true });
writeFileSync(
    join(root, 'resources/icons/lucide.php'),
    `<?php\n\n// Generated by scripts/hydra-lucide-icons.mjs from lucide ${version} (ISC license). Do not edit.\nreturn ${php(icons)};\n`
);

console.log(`Exported ${Object.keys(icons).length} Lucide ${version} icons.`);
